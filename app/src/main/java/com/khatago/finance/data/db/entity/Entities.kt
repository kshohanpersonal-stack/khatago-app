    val createdAt: Long = 0,
)

/**
 * Notification dedupe ledger: one row per (obligation, calendar day) a reminder was posted for.
 * "No spam" is therefore a structural property enforced by a UNIQUE index, not a promise in the
 * notification code.
 */
@Entity(
    tableName = "reminder_log",
    indices = [
        Index(value = ["dedupeKey"], unique = true),
        Index("dueDateEpochDay"),
    ],
)
