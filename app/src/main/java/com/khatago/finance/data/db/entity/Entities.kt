import androidx.room.PrimaryKey
import kotlinx.serialization.Transient

/**
 * KhataGo's persisted schema (Room database version 1).
 *
 * Three rules govern every entity here, and they are the reason the money model is trustworthy:
 *
 * 1. **Amounts are `Long` minor units.** No `Float`, no `Double`, no numeric strings. `10050`
 *    means ৳100.50. A `REAL` column would eventually print ৳0.30000000000000004 in a report.
 * 2. **No derived amount is stored.** There is no `remaining` / `totalPaid` column on any
 *    obligation: those are computed from the payment ledger on every read (see `FinancialMath`).
 *    A stored total drifts the moment a payment is edited or deleted, and a drifted number in a
 *    money app is a bug the user discovers months later.
 * 3. **Dates that mean something to a human are epoch-day integers** (a local calendar day), not
 *    instants, so a due date never shifts across a timezone or DST change. Machine timestamps use
 *    epoch milliseconds.
 *
 * Column names follow the Kotlin property names (Room's default) — deliberately, not lazily:
 * a single naming rule means hand-written aggregate SQL and the projection classes below it can
 * never disagree about whether a column is `amountMinor` or `amount_minor`.
 *
 * Property names are also the backup JSON field names, so the export format is readable and
 * stable. `app/schemas/<table>/1.json` is generated by the build and is the source of truth for
 * migrations.
 */

@Entity(tableName = "profile")
data class ProfileEntity(
    @PrimaryKey(autoGenerate = true) @Transient val id: Long = 0,
    val displayName: String? = null,
    val currencyCode: String = "BDT",
    val countryCode: String? = null,
    val avatarUri: String? = null,
    /** 0 means "goal not set" — distinct from a genuine ৳0 target. */
    val monthlyIncomeGoalMinor: Long = 0,
    val monthlyExpenseGoalMinor: Long = 0,
    val onboardingComplete: Boolean = false,
    val createdAt: Long = 0,
    val updatedAt: Long = 0,
)

/**
 * A shop the user buys from on credit. No denormalised balance columns: a shop's outstanding
 * amount is always the sum of its credits minus the payments recorded against those credits.
 */
@Entity(
    tableName = "shops",
    indices = [Index(value = ["name"], unique = true)],
)
data class ShopEntity(
    @PrimaryKey(autoGenerate = true) @Transient val id: Long = 0,
    val name: String,
    val ownerName: String? = null,
    val phone: String? = null,
    val address: String? = null,
    val category: String? = null,
    val notes: String? = null,
    val photoUri: String? = null,
    val archived: Boolean = false,
    val createdAt: Long = 0,
    val updatedAt: Long = 0,
)

/**
 * A single credit purchase at a shop — one line of the market khata.
 *
 * `quantity x unitPriceMinor` is kept next to `totalAmountMinor` rather than replacing it: the
 * agreed notebook total sometimes includes a discount or rounding the user wants to keep exactly.
 * The repository validates that the two agree unless `overrideTotal` says the total was typed on
 * purpose, so a mistyped unit price cannot silently rewrite what is owed.
 */
@Entity(
    tableName = "shop_credits",
    indices = [Index("shopId"), Index("dueDateEpochDay"), Index("purchaseDateEpochDay"), Index("cancelled")],
    foreignKeys = [
        ForeignKey(
            entity = ShopEntity::class,
            parentColumns = ["id"],
            childColumns = ["shopId"],
            onDelete = ForeignKey.CASCADE,
        ),
    ],
)
data class ShopCreditEntity(
    @PrimaryKey(autoGenerate = true) @Transient val id: Long = 0,
    val shopId: Long,
    val productName: String,
    val quantity: Long = 1,
    val unitPriceMinor: Long = 0,
    val totalAmountMinor: Long,
    val overrideTotal: Boolean = false,
    val purchaseDateEpochDay: Long,
    val dueDateEpochDay: Long? = null,
    val notes: String? = null,
    val cancelled: Boolean = false,
    val createdAt: Long = 0,
    val updatedAt: Long = 0,
)

/**
 * A person the user has money with. One row can hold both borrowings (the user owes them) and
 * lendings (they owe the user): a single identity table is what stops "Karim" becoming two
 * unrelated records with split balances.
 */
@Entity(
    tableName = "people",
    indices = [Index(value = ["name", "relationship"], unique = true)],
)
data class PersonEntity(
    @PrimaryKey(autoGenerate = true) @Transient val id: Long = 0,
    val name: String,
    val relationship: String = RELATIONSHIP_OTHER,
    val phone: String? = null,
    val notes: String? = null,
    val photoUri: String? = null,
    val createdAt: Long = 0,
    val updatedAt: Long = 0,
) {
    companion object {
        val RELATIONSHIPS = listOf("Friend", "Relative", "Family", "Colleague", "Neighbor", "Other")
        const val RELATIONSHIP_OTHER = "Other"
    }
}

