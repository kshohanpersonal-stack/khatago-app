/**
 * An image (receipt, product photo, agreement page) attached to a record.
 *
 * Files live in the app's private `attachments/` directory, downscaled and recompressed at import
 * so a 12 MP camera JPEG cannot blow up memory or storage. Only the file name is persisted, so a
 * reinstall can re-resolve the path; a missing file degrades to "attachment unavailable" rather
 * than a broken screen.
 */
@Entity(
    tableName = "attachments",
    indices = [Index(value = ["targetType", "targetId"])],
)
data class AttachmentEntity(
    @PrimaryKey(autoGenerate = true) @Transient val id: Long = 0,
    val targetType: String,
    val targetId: Long,
    val fileName: String,
    val originalName: String? = null,
    val mimeType: String = "image/jpeg",
    val sizeBytes: Long = 0,
    val createdAt: Long = 0,
) {
    companion object {
        const val TARGET_SHOP = "shop"
        const val TARGET_SHOP_CREDIT = "shop_credit"
        const val TARGET_PERSON = "person"
        const val TARGET_LOAN = "loan"
        const val TARGET_EMI = "emi"
        const val TARGET_BORROWING = "borrowing"
        const val TARGET_LENDING = "lending"
        const val TARGET_INCOME = "income"
        const val TARGET_EXPENSE = "expense"
        const val TARGET_PAYMENT = "payment"
    }
}

/**
 * A user-authored reminder. Automatic due reminders are *derived* from due dates and need no rows;
 * this table is for the notes-to-self a person adds deliberately ("collect the deed paper on the
 * 9th"). Included in backups for completeness.
 */
@Entity(
    tableName = "reminders",
    indices = [Index("dueDateEpochDay"), Index(value = ["entityType", "entityId"])],
)
data class ReminderEntity(
    @PrimaryKey(autoGenerate = true) @Transient val id: Long = 0,
    val entityType: String? = null,
    val entityId: Long? = null,
    val title: String,
