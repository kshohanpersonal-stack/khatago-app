/**
 * One scheduled repayment of a loan or an EMI purchase.
 *
 * `ownerType` + `ownerId` is a discriminated link (same mechanism as the payment ledger) because a
 * loan installment and an EMI installment behave identically; duplicating the table would double
 * every query and every bug. `paidMinor` records only what was paid at this line — the
 * authoritative per-line position is computed by `InstallmentAllocator`, which is what guarantees
 * the schedule can never contradict the obligation's headline balance.
 */
@Entity(
    tableName = "installments",
    indices = [
        Index(value = ["ownerType", "ownerId"]),
        Index("dueDateEpochDay"),
    ],
)
data class InstallmentEntity(
    @PrimaryKey(autoGenerate = true) @Transient val id: Long = 0,
    val ownerType: String,
    val ownerId: Long,
    val number: Int,
    val dueDateEpochDay: Long,
    val scheduledAmountMinor: Long,
    val paidMinor: Long = 0,
    /** True when the user edited the line, so a schedule regeneration must not clobber it. */
    val manual: Boolean = false,
    val createdAt: Long = 0,
)

/**
 * The payment ledger: the only place KhataGo records money actually moving against an obligation.
 *
 * Payments are independent rows linked by (payableType, payableId), which is what makes editing or
 * deleting a payment safe — balances are recomputed and history is never destructively merged into
 * the obligation.
 */
@Entity(
    tableName = "payments",
    indices = [
        Index(value = ["payableType", "payableId"]),
        Index("paidDateEpochDay"),
        Index("installmentId"),
    ],
    // payableId is intentionally NOT a foreign key. It is polymorphic (shop_credits, loans,
    // emi_purchases, borrowings or lendings, chosen by payableType) and SQLite cannot express
    // "FK into one of five tables" — a one-table FK would silently accept an unrelated row whose
    // id happens to collide. Referential integrity is enforced in the repository layer instead,
    // in the same transaction as the delete, and is covered by database tests.
    foreignKeys = [
        ForeignKey(
            entity = InstallmentEntity::class,
            parentColumns = ["id"],
            childColumns = ["installmentId"],
            onDelete = ForeignKey.SET_NULL,
        ),
    ],
)
data class PaymentEntity(
    @PrimaryKey(autoGenerate = true) @Transient val id: Long = 0,
    val payableType: String,
    val payableId: Long,
    val installmentId: Long? = null,
    val amountMinor: Long,
    val paidDateEpochDay: Long,
    val methodName: String = "Cash",
    val reference: String? = null,
    val note: String? = null,
    val createdAt: Long = 0,
    val updatedAt: Long = 0,
)

@Entity(
